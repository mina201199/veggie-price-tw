const assert=require('node:assert/strict'),fs=require('node:fs');
assert.ok(fs.existsSync(__dirname+'/notes-store.js'),'Private notebook storage module is required');
const N=require('./notes-store.js');
const memory={value:null,getItem(){return this.value},setItem(k,v){this.value=v}};
const store=N.createStore(memory);
const input={venue:'測試全聯・測試分店',product:'雞胸肉',brand:'測試品牌',date:'2026-10-01',price:'89',quantity:'300',unit:'g',freshness:'這次覺得新鮮',notes:'私人內容',share:true};
const first=store.save(input);assert.equal(store.load().length,1);
assert.equal(N.perKg(N.latest(first)),296.6666666666667);
store.save({...input,price:'95'},first.id);
const reread=N.createStore(memory).load()[0];assert.equal(reread.versions.length,2);assert.equal(reread.versions[0].price,89);assert.equal(N.latest(reread).price,95);
store.save(input);assert.equal(store.load().length,2,'New purchase is not a revision');
const shared=N.sharePayload(N.latest(reread));assert.equal(shared.price,95);assert.ok(!('notes' in shared));assert.ok(!('freshness' in shared));assert.ok(!('repurchase' in shared));
assert.equal(N.sharePayload({...input,share:false}),null);
assert.equal(N.perKg({...input,unit:'包'}),null,'Unknown package weight must not be invented');
assert.equal(N.perKg({...input,price:60,quantity:1,unit:'台斤'}),100);
for(const price of ['','-1','abc','Infinity'])assert.throws(()=>store.save({...input,price}));
assert.throws(()=>store.save({...input,quantity:0}));assert.throws(()=>store.save({...input,date:'2026-02-30'}));
assert.throws(()=>store.save(input,'missing'));
const blocked=N.createStore({getItem(){return null},setItem(){throw Error('quota')}});assert.throws(()=>blocked.save(input));assert.equal(blocked.load().length,0);
const corrupt=N.createStore({getItem(){return 'broken'},setItem(){throw Error('must not overwrite')}});assert.throws(()=>corrupt.load());assert.throws(()=>corrupt.save(input));
const exported=JSON.parse(store.exportJSON());assert.equal(exported.records[0].versions.length,2);
const quick=store.save({venue:'測試攤',product:'高麗菜',price:50,date:'2026-10-07',quantity:'',unit:'g'});
assert.equal(N.latest(quick).quantity,null);
assert.equal(N.latest(quick).unit,'');
assert.equal(N.perKg(N.latest(quick)),null);
assert.equal(N.sharePayload({...N.latest(quick),share:true}),null,'Incomplete quantity cannot become comparable public price');
assert.equal(store.load().length,3,'New optional quantities and old full records must load together');
assert.equal(N.perKg({price:50,quantity:null,unit:'g'}),null);
const rated=store.save({...input,experience:'優秀'});
assert.equal(N.latest(store.load().find(r=>r.id===rated.id)).experience,'優秀');
store.save({...input,experience:'普通'},rated.id);
const ratedVersions=store.load().find(r=>r.id===rated.id).versions;
assert.equal(ratedVersions[0].experience,'優秀');
assert.equal(ratedVersions[1].experience,'普通');
assert.equal(N.validate(input).experience,'','Older notes have no inferred overall rating');
assert.equal(N.validate({...input,experience:''}).experience,'');
assert.ok(!('experience' in N.sharePayload(N.latest(rated))),'Overall rating must remain private');
assert.throws(()=>N.validate({...input,experience:'invalid'}));
console.log('Shopping notes: persistence, revisions, optional quantity, private experience rating, units and failure safety PASS');
