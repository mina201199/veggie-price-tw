const assert = require('node:assert/strict');
const fs = require('node:fs');
assert.ok(fs.existsSync(__dirname+'/shopping-flow.js'), '採買流程模組尚未建立');
const F = require('./shopping-flow.js');
const N = require('./notes-store.js');
const memory=()=>{const data=new Map();return {getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};};
const storage=memory(),plan=F.createPlan(storage,'local');
plan.add('高麗菜');plan.add('高麗菜');plan.add('牛奶');
assert.deepEqual(plan.load(),['高麗菜','牛奶']);
plan.remove('高麗菜');assert.deepEqual(plan.load(),['牛奶']);
assert.deepEqual(F.createPlan(storage,'account-2').load(),[],'帳號清單需分開');
storage.setItem(F.planKey('broken'),'{');
assert.throws(()=>F.createPlan(storage,'broken').add('高麗菜'),/讀取/,'毀損清單不能被覆蓋');
const r=(product,price,quantity,unit,date,spec='')=>({versions:[{product,venue:'市場',price,quantity,unit,date,spec,brand:'',origin:'',promo:''}]});
const records=[r('高麗菜',60,1,'台斤','2026-10-10'),r('高麗菜',50,500,'g','2026-10-11'),r('牛奶',80,1,'盒','2026-10-12')];
assert.equal(F.lastPurchase(records,'高麗菜','2026-10-13').price,50);
assert.equal(F.lastPurchase(records,'高麗菜','2026-10-10').price,60,'不拿未來購買當上次');
assert.equal(F.compare(records[1].versions[0],{price:120,quantity:1,unit:'kg'}).percent,20,'不同重量用公斤價比較');
assert.equal(F.compare(records[2].versions[0],{price:90,quantity:2,unit:'盒'}).percent,-43.75,'同數量單位可比較');
assert.equal(F.compare(records[2].versions[0],{price:90,quantity:1,unit:'包'}),null,'不同非重量單位不可硬比');
assert.equal(F.compare(records[0].versions[0],{price:100,quantity:'',unit:''}),null,'沒有重量不判斷漲跌');
assert.deepEqual(F.frequent(records,'2026-10-13').map(n=>n.product),['高麗菜','牛奶']);
const draft=F.draft({name:'高麗菜',official:'甘藍-初秋'},'60','1','公斤');
assert.equal(draft.unit,'kg');assert.equal(draft.spec,'甘藍-初秋');
assert.equal(draft.venue,'');assert.equal(draft.share,false);
F.putDraft(storage,'local',draft);assert.deepEqual(F.takeDraft(storage,'account-2'),null);
assert.equal(F.takeDraft(storage,'local').product,'高麗菜');assert.equal(F.takeDraft(storage,'local'),null,'交接只讀一次');
const notes=N.createStore(memory());
assert.throws(()=>notes.save({...draft,date:'2026-10-13'}),/分店/,'未確認店家不可直接儲存');
notes.save({...draft,venue:'市場',date:'2026-10-13'});plan.remove(draft.product);
assert.equal(notes.load().length,1);assert.equal(N.latest(notes.load()[0]).quantity,1);
console.log('PASS: 清單持續保存、帳號隔離、歷史比較、單位換算與採買交接');
